import { useEffect, useState } from "react";
import { getLatestResponsePlan } from "../../api/api";

function ResponsePlan() {
  const [incidents, setIncidents] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  useEffect(() => {
    async function fetchResponsePlan() {
      try {
        setLoading(true);
        setError("");

        const data = await getLatestResponsePlan();

        setIncidents(data.plan_data?.incidents || []);
      } catch (err) {
        console.error("Failed to fetch response plan:", err);
        setError("Unable to load response plan.");
      } finally {
        setLoading(false);
      }
    }

    fetchResponsePlan();
  }, []);

  return (
    <section className="mt-6 overflow-hidden rounded-xl border border-slate-800 bg-slate-900/70">
      {/* Header */}
      <div className="border-b border-slate-800 px-6 py-5">
        <h2 className="text-sm font-semibold tracking-[0.14em] text-white">
          RESPONSE PLAN
        </h2>

        <p className="mt-1 text-xs text-slate-500">
          Consolidated response plan generated by the AI agent
        </p>
      </div>

      {/* Loading */}
      {loading && (
        <div className="px-6 py-6">
          <p className="text-xs text-slate-500">
            Loading response plan...
          </p>
        </div>
      )}

      {/* Error */}
      {!loading && error && (
        <div className="border-b border-slate-800 px-6 py-6">
          <p className="text-xs text-red-400">{error}</p>
        </div>
      )}

      {/* No plan */}
      {!loading && !error && incidents.length === 0 && (
        <div className="px-6 py-6">
          <p className="text-xs text-slate-500">
            No response plan available.
          </p>
        </div>
      )}

      {/* Table */}
      {!loading && !error && incidents.length > 0 && (
        <div className="overflow-x-auto">
          <table className="w-full min-w-[600px] text-center">
            <thead>
              <tr className="border-b border-slate-800">
                <th className="px-6 py-3 text-[10px] font-semibold tracking-[0.14em] text-slate-500">
                  INCIDENT
                </th>

                <th className="px-6 py-3 text-[10px] font-semibold tracking-[0.14em] text-slate-500">
                  PRIORITY
                </th>

                <th className="px-6 py-3 text-[10px] font-semibold tracking-[0.14em] text-slate-500">
                  RESPONSE
                </th>
              </tr>
            </thead>

            <tbody>
              {incidents.map((incident) => (
                <ResponsePlanRow
                  key={incident.incident_id}
                  incident={incident}
                />
              ))}
            </tbody>
          </table>
        </div>
      )}

      {/* Footer */}
      {!loading && !error && (
        <div className="border-t border-slate-800 px-6 py-3">
          <p className="text-xs text-slate-600">
            {incidents.length} incidents included in current response plan
          </p>
        </div>
      )}
    </section>
  );
}

function ResponsePlanRow({ incident }) {
  const priorityStyles = {
    CRITICAL: "text-red-400",
    HIGH: "text-orange-400",
    MODERATE: "text-yellow-400",
    LOW: "text-slate-400",
  };

  return (
    <tr className="border-b border-slate-800/70 transition hover:bg-slate-800/30">
      <td className="px-6 py-4">
        <span className="text-sm font-semibold text-white">
          #{incident.incident_id}
        </span>
      </td>

      <td className="px-6 py-4">
        <span
          className={`text-xs font-semibold tracking-wider ${
            priorityStyles[incident.priority] || priorityStyles.LOW
          }`}
        >
          {incident.priority}
        </span>
      </td>

      <td className="px-6 py-4">
        <div className="flex flex-wrap justify-center gap-2">
          {incident.recommended_actions.map((action, index) => (
            <span
              key={`${action.action}-${action.resource_id || index}`}
              className="rounded-md border border-slate-700 bg-slate-950/50 px-2.5 py-1 text-xs font-medium text-slate-300"
            >
              {action.resource_id || "MONITOR"}
            </span>
          ))}
        </div>
      </td>
    </tr>
  );
}

export default ResponsePlan;